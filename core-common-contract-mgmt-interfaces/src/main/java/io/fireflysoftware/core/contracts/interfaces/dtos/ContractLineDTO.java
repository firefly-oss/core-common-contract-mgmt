package io.fireflysoftware.core.contracts.interfaces.dtos;

import com.fasterxml.jackson.annotation.JsonProperty;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.UUID;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ContractLineDTO {

    @JsonProperty(access = JsonProperty.Access.READ_ONLY)
    private UUID contractLineId;

    private UUID contractId;

    @NotNull(message = "Product ID is required")
    private UUID productId;

    @Size(max = 50, message = "Line role must not exceed 50 characters")
    private String lineRole;

    @DecimalMin(value = "0.0", inclusive = true, message = "Quantity must be non-negative")
    private BigDecimal quantity;

    private LocalDateTime effectiveFrom;
    private LocalDateTime effectiveTo;
    private Boolean isPrimary;

    @JsonProperty(access = JsonProperty.Access.READ_ONLY)
    private LocalDateTime createdAt;

    @JsonProperty(access = JsonProperty.Access.READ_ONLY)
    private LocalDateTime updatedAt;
}
